// Detect saved language first
const savedLanguage = localStorage.getItem("cvLanguage");


// Otherwise detect browser language
const browserLanguage =
  navigator.language.toLowerCase();


let defaultLanguage = "en";

if (browserLanguage.startsWith("fr")) {
  defaultLanguage = "fr";
}

else if (browserLanguage.startsWith("de")) {
  defaultLanguage = "de";
}

else if (
  browserLanguage.startsWith("ar")
) {
  defaultLanguage = "ar";
}


changeLanguage(savedLanguage || defaultLanguage);